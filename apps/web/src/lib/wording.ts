/**
 * 画面に出す言葉を 1 箇所に集める。
 *
 * **同じ意味に違う言葉を使わない。** 以前は削除が「削除」「消す」「外す」の
 * 3 通りに分かれていた。利用者は別の操作だと思う。
 */
export const WORDING = Object.freeze({
  /** 取り消せない削除。対象を必ず添えること（例: `${WORDING.delete}（Look）`）。 */
  delete: '削除',
  /** 関連づけを外すだけで、対象そのものは消えない操作。 */
  unlink: '解除',
  cancel: 'やめる',
  save: '保存',
  /** 時間のかかる処理の開始。押しても完了はしない。 */
  start: '実行',
  reload: '再読み込み',
  /** 結果を引き直す。自動で更新されない画面で使う。 */
  refresh: '最新の状態にする',
})

/** 削除の確認文。**何が消えるかと、戻せないことを必ず書く。** */
export const deleteConfirmMessage = (target: string): string =>
  `${target}を削除します。元に戻せません。`
